"""
grpc_service/meal_server.py
============================
gRPC Server — Experiment 3: Distributed Computing

This server implements the MealService defined in:
    grpc_service/proto/meal_service.proto

Architecture:
  - Runs as a standalone process (separate from the Flask web app).
  - Listens on port 50051 for gRPC connections.
  - Loads meal nutrition data from the existing Dataset/ CSV files.
  - Demonstrates Lamport logical clock for distributed event ordering.

How gRPC works here:
  1. Client sends MealRequest (meal_name + Lamport timestamp).
  2. Server updates its Lamport clock:  max(server, client) + 1
  3. Server looks up nutrition in the datasets.
  4. Server ticks its Lamport clock for the response event.
  5. Server returns MealResponse (nutrition + server Lamport timestamp).
"""

